"""Data models exchanged between the orchestrator and the LLM layer."""

from typing import Literal
from pydantic import BaseModel, Field

Role = Literal["system", "user", "assistant"]


class Message(BaseModel):
    """One chat message, in the format expected by OpenAI-compatible APIs.

    The conversation sent to the LLM is a list of these: the system prompt
    first, then alternating user turns (task, observations) and assistant
    turns (the model's previous answers).
    """

    role: Role
    content: str


class LLMResponse(BaseModel):
    """The model's answer to one request, with the metrics of that request.

    The orchestrator copies these metrics into ``StepMetrics`` for the
    current step: every field below except ``text`` has a field of the same
    name there.
    """

    text: str = Field(description="Raw text generated by the model")
    input_tokens: int = Field(ge=0, description="Prompt tokens billed")
    output_tokens: int = Field(
        ge=0, description="Generated tokens, reasoning tokens included"
    )
    request_time_ms: float = Field(
        ge=0, description="Wall-clock time of the call, retries included"
    )
    retries: int = Field(
        ge=0, description="Failed attempts before the successful one"
    )
    api_url: str = Field(description="Base URL of the provider that answered")
    model_name: str = Field(description="Model identifier that answered")
